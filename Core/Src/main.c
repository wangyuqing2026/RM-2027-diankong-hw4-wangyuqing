/* 作业要求的 5 个定角：0 -> 45 -> 90 -> 135 -> 180 */
static const float SERVO_SEQ[5] = {0.0f, 45.0f, 90.0f, 135.0f, 180.0f};

/**
  * @brief  printf 重定向到 USART1（GCC / newlib 版本）
  *
  * CLion + arm-none-eabi-gcc 用的是 newlib，printf 最终会调用 _write()。
  * CubeMX 在 Core/Src/syscalls.c 里放了一个 __attribute__((weak)) 的 _write，
  * 我们在这里重新定义同名函数，链接器会优先用这个"强符号"，
  * 于是 printf 的内容就顺着 USART1 发出去了。
  *
  * 注意：Keil MDK 那边写的是 fputc / __io_putchar，跟 GCC 不是一回事，照抄会报错。
  */
int _write(int fd, char *ptr, int len)
{
  (void)fd;
  HAL_UART_Transmit(&huart1, (uint8_t *)ptr, (uint16_t)len, 100);
  return len;
}
